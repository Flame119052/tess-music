// Spicetify loads one stylesheet (user.css) and one script (theme.js) per theme.
// The sources live in theme/Tess/src/; this joins them into those two files.
// Usage: node tools/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../theme/Tess/', import.meta.url));
const parts = { 'user.css': ['core.css', 'home.css'], 'theme.js': ['core.js', 'home.js'] };
const banner = (f) => (f.endsWith('.css') ? '/* Generated by tools/build.mjs from theme/Tess/src/ — edit those files. */\n' : '// Generated by tools/build.mjs from theme/Tess/src/ — edit those files.\n');
for (const [out, srcs] of Object.entries(parts)) {
  writeFileSync(dir + out, banner(out) + srcs.map((s) => readFileSync(dir + 'src/' + s, 'utf8')).join('\n'));
}
console.log('built user.css, theme.js');
